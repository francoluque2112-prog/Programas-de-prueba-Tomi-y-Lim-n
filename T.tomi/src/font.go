// DrawText draws a string with shadow and optional scaling (scale=1 -> 8x12, scale=2 -> 16x24, etc.)
func (fb *Framebuffer) DrawText(x, y int, text string, scale int, c color.RGBA, withShadow bool) {
	if scale < 1 {
		scale = 1
	}

	if withShadow {
		shadowColor := color.RGBA{0, 0, 0, 180}
		fb.drawTextRaw(x+scale, y+scale, text, scale, shadowColor)
	}
	fb.drawTextRaw(x, y, text, scale, c)
}

func (fb *Framebuffer) drawTextRaw(startX, startY int, text string, scale int, c color.RGBA) {
	curX := startX
	curY := startY
	charW := 8 * scale
	charH := 12 * scale

	for _, r := range text {
		if r == '\n' {
			curX = startX
			curY += charH + 2*scale
			continue
		}

		glyph, ok := defaultFont[r]
		if !ok {
			glyph, ok = defaultFont['?']
			if !ok {
				curX += charW
				continue
			}
		}

		for row := 0; row < 12; row++ {
			b := glyph[row]
			for col := 0; col < 8; col++ {
				if (b & (0x80 >> col)) != 0 {
					fb.DrawFilledRect(curX+col*scale, curY+row*scale, scale, scale, c)
				}
			}
		}

		curX += charW
	}
}

// MeasureText returns the pixel width and height of a string at given scale
func MeasureText(text string, scale int) (int, int) {
	if scale < 1 {
		scale = 1
	}
	charW := 8 * scale
	charH := 12 * scale

	maxW := 0
	lines := 1
	curW := 0

	for _, r := range text {
		if r == '\n' {
			if curW > maxW {
				maxW = curW
			}
			curW = 0
			lines++
			continue
		}
		curW += charW
	}
	if curW > maxW {
		maxW = curW
	}

	return maxW, lines * (charH + 2*scale)
}
